// dev/lx/bundleAndroidLx.mjs
// Bundles the LX core for the Android app (Capacitor WebView): capacitor/lx/androidCore.js (the desktop
// bridge, managers and vendored musicSdk with Node's modules swapped for capacitor/lx/shims) and
// capacitor/lx/scriptWorker.js (the source script runtime in a Web Worker) into ES modules under
// src/services/onlineMusic/lx/android/generated/. Run with `npm run build:lx-android` after changing
// anything under electron/lx/ or capacitor/lx/; the output is committed like electron/lx/musicSdk/lxMusicSdk.cjs.
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'rolldown';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const sdkDir = path.join(root, 'electron/lx/musicSdk');
const shims = path.join(root, 'capacitor/lx/shims');
const outDir = path.join(root, 'src/services/onlineMusic/lx/android/generated');

const NODE_SHIMS = {
    fs: 'fs.js', path: 'path.js', crypto: 'crypto.js', zlib: 'zlib.js', dns: 'dns.js', vm: 'vm.js',
    http: 'empty.js', https: 'empty.js', url: 'empty.js',
};

// Node built-ins (bare or node:) to the shims; inside node_modules a `crypto` probe (node-forge) gets an
// empty module, so the shim that uses node-forge does not import itself.
const nodeShimPlugin = {
    name: 'folia-lx-node-shims',
    resolveId(source, importer) {
        const bare = source.startsWith('node:') ? source.slice(5) : source;
        if (bare === 'buffer') return null;
        if (!(bare in NODE_SHIMS)) return null;
        if (importer && importer.includes(`${path.sep}node_modules${path.sep}`)) return path.join(shims, 'empty.js');
        return path.join(shims, NODE_SHIMS[bare]);
    },
};

const banner = (name, entry) => [
    `// src/services/onlineMusic/lx/android/generated/${name}`,
    `// GENERATED by \`npm run build:lx-android\` (dev/lx/bundleAndroidLx.mjs) from ${entry} - do not edit by hand.`,
    '// Contains code from lyswhut/lx-music-desktop (Apache-2.0); see electron/lx/musicSdk/NOTICE.md and capacitor/lx/NOTICE.md.',
    '/* eslint-disable */',
    '// @ts-nocheck',
].join('\n');

const common = {
    platform: 'browser',
    plugins: [nodeShimPlugin],
    resolve: {
        alias: {
            '@renderer/utils/musicSdk/kg/vendors/infSign.min': path.join(sdkDir, 'src/kg/vendors/infSign.min.js'),
            '@common/utils/lyricUtils/kg': path.join(sdkDir, 'src/kgKrc.js'),
            '@renderer/utils': path.join(sdkDir, 'index.js'),
        },
    },
    transform: { define: { 'process.env.NODE_ENV': '"production"' } },
};

for (const [entry, file] of [['capacitor/lx/androidCore.js', 'lxAndroidCore.js'], ['capacitor/lx/scriptWorker.js', 'lxScriptWorker.js']]) {
    await build({
        ...common,
        input: path.join(root, entry),
        output: {
            file: path.join(outDir, file),
            format: 'esm',
            codeSplitting: false,
            banner: banner(file, entry),
        },
    });
    console.log(`[lx] bundled src/services/onlineMusic/lx/android/generated/${file}`);
}
