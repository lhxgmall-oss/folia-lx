// dev/lx/bundleMusicSdk.mjs
// Bundles the vendored LX Music musicSdk subset (electron/lx/musicSdk/entry.js and ./src) into one
// CommonJS file the main process can require: electron/lx/musicSdk/lxMusicSdk.cjs. Run with
// `npm run build:lx-sdk` after changing anything under electron/lx/musicSdk/.
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'rolldown';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const sdkDir = path.join(root, 'electron/lx/musicSdk');

await build({
    input: path.join(sdkDir, 'entry.js'),
    platform: 'node',
    // The kg vendor file reads navigator.userAgent at load; the main process may have no navigator.
    resolve: {
        alias: {
            '@renderer/utils/musicSdk/kg/vendors/infSign.min': path.join(sdkDir, 'src/kg/vendors/infSign.min.js'),
            '@common/utils/lyricUtils/kg': path.join(sdkDir, 'src/kgKrc.js'),
            '@renderer/utils': path.join(sdkDir, 'index.js'),
        },
    },
    external: [/^node:/, 'crypto', 'zlib', 'dns', 'http', 'https', 'url', 'buffer'],
    output: {
        file: path.join(sdkDir, 'lxMusicSdk.cjs'),
        format: 'cjs',
        exports: 'named',
        banner: [
            '// electron/lx/musicSdk/lxMusicSdk.cjs',
            '// GENERATED by `npm run build:lx-sdk` (dev/lx/bundleMusicSdk.mjs) - do not edit by hand.',
            '// Contains code from lyswhut/lx-music-desktop (Apache-2.0); see electron/lx/musicSdk/NOTICE.md.',
            '/* eslint-disable */',
            "var navigator = (typeof globalThis.navigator === 'object' && globalThis.navigator) || { userAgent: '' };",
        ].join('\n'),
    },
});
console.log('[lx] bundled electron/lx/musicSdk/lxMusicSdk.cjs');
